func pppOptionsPath(stateDir, name string) string {
	return filepath.Join(stateDir, "ppp", name+".options")
}

func xl2tpdConfigPath(stateDir string) string {
	return filepath.Join(stateDir, "xl2tpd.conf")
}

func xl2tpdControlPath(stateDir string) string {
	return filepath.Join(stateDir, "xl2tpd.control")
}

func xl2tpdPIDPath(stateDir string) string {
	return filepath.Join(stateDir, "xl2tpd.pid")
}

func swanctlPath(dir, name string) string {
	return filepath.Join(dir, "tunneld-"+name+".conf")
}

func linkStatePath(stateDir, name string) string {
	return filepath.Join(stateDir, "ifaces", name)
}

// generatePPP writes the pppd options for one tunnel. The file contains a
// password and is therefore always mode 0600.
func generatePPP(cfg *config.Config, secrets *config.SecretStore, t config.Tunnel) (string, error) {
	pass, ok := secrets.Get(t.PasswordRef)
	if !ok || pass == "" {
		return "", fmt.Errorf("no password is stored for tunnel %s", t.Name)
	}
	var b strings.Builder
	b.WriteString("# Generated by tunneld. Do not edit: changes are overwritten.\n")
	b.WriteString("# This file contains a credential and must remain mode 0600.\n")
	if t.Method == config.MethodPPTP {
		b.WriteString("# WARNING: PPTP is deprecated and provides weak encryption.\n")
	}
	b.WriteString("noauth\n")
	b.WriteString("nodefaultroute\n")
	b.WriteString("noipdefault\n")
	b.WriteString("nopersist\n")
	b.WriteString("nolock\n")
	b.WriteString("nocrtscts\n")
	b.WriteString("hide-password\n")
	b.WriteString("logfd 2\n")
	b.WriteString("ipparam " + quotePPPOption(t.Name) + "\n")
	b.WriteString("user " + quotePPPOption(t.Username) + "\n")
	b.WriteString("password " + quotePPPOption(pass) + "\n")
	b.WriteString(fmt.Sprintf("mtu %d\nmru %d\n", t.MTU, t.MRU))
	b.WriteString("lcp-echo-interval 20\nlcp-echo-failure 3\n")
	b.WriteString("require-mschap-v2\n")

	switch t.Method {
	case config.MethodL2TP:
		b.WriteString("noccp\n")
	case config.MethodSSTP:
		b.WriteString("noccp\n")
		host := net.JoinHostPort(t.Server, strconv.Itoa(t.SSTPPort))
		args := []string{
			cfg.Commands.Sstpc, "--nolaunchpppd", "--log-stderr", "--log-level", "4",
			"--save-server-route",
		}
		if t.SSTPIgnoreCert {
			args = append(args, "--cert-warn")
		} else if t.SSTPCACert != "" {
			args = append(args, "--ca-cert", t.SSTPCACert)
		}
		args = append(args, host)
		b.WriteString("pty " + quotePPPOption(joinShellArgs(args)) + "\n")
	case config.MethodPPTP:
		if t.RequireMPPE {
			b.WriteString("require-mppe-128\n")
		}
		args := []string{cfg.Commands.Pptp, t.Server, "--nolaunchpppd", "--nohostroute", "--logstring", "tunneld-" + t.Name}
		if t.PPTPPhone != "" {
			args = append(args, "--phone", t.PPTPPhone)
		}
		b.WriteString("pty " + quotePPPOption(joinShellArgs(args)) + "\n")
	}
	return b.String(), nil
}

// generateXL2TPD writes one xl2tpd configuration containing every enabled
// L2TP LAC. Tunnel names are the control identity, not PPP interface numbers.
func generateXL2TPD(cfg *config.Config, tunnels []config.Tunnel) string {
	var b strings.Builder
	b.WriteString("; Generated by tunneld. Do not edit: changes are overwritten.\n")
	b.WriteString("[global]\n")
	b.WriteString("port = 1701\n")
	b.WriteString("access control = no\n")
	b.WriteString("rand source = dev\n\n")
	for _, t := range tunnels {
		if t.Method != config.MethodL2TP || !t.Enabled {
			continue
		}
		b.WriteString("[lac " + t.Name + "]\n")
		b.WriteString("lns = " + t.Server + "\n")
		b.WriteString("name = tunneld-" + t.Name + "\n")
		b.WriteString("pppoptfile = " + pppOptionsPath(cfg.StateDir, t.Name) + "\n")
		b.WriteString("require authentication = yes\n")
		b.WriteString("redial = no\n")
		b.WriteString("length bit = yes\n")
		b.WriteString("ppp debug = no\n\n")
	}
	return b.String()
}

// generateSwanctl writes an IKEv1 transport-mode connection for L2TP/IPsec.
// The PSK lives only in this 0600 file, never in the public configuration.
func generateSwanctl(cfg *config.Config, secrets *config.SecretStore, t config.Tunnel) (string, error) {
	psk, ok := secrets.Get(t.IPSecSecretRef)
	if !ok || psk == "" {
		return "", fmt.Errorf("no IPsec pre-shared key is stored for tunnel %s", t.Name)
	}
	name := "tunneld-" + t.Name
	var b strings.Builder
	b.WriteString("# Generated by tunneld. Contains a pre-shared key; keep mode 0600.\n")
	b.WriteString("connections {\n")
	b.WriteString("  " + name + " {\n")
	b.WriteString("    version = 1\n")
	b.WriteString("    local_addrs = %any\n")
	b.WriteString("    remote_addrs = " + t.Server + "\n")
	b.WriteString("    proposals = aes256-sha256-modp2048,aes128-sha256-modp2048,aes256-sha1-modp1024,aes128-sha1-modp1024,default\n")
	b.WriteString("    local { auth = psk }\n")
	b.WriteString("    remote { auth = psk }\n")
	b.WriteString("    send_certreq = no\n")
	b.WriteString("    children {\n")
	b.WriteString("      " + name + " {\n")
	b.WriteString("        local_ts = dynamic[udp/1701]\n")
	b.WriteString("        remote_ts = dynamic[udp/1701]\n")
	b.WriteString("        mode = transport\n")
	b.WriteString("        esp_proposals = aes256-sha256,aes128-sha256,aes256-sha1,aes128-sha1,default\n")
	b.WriteString("        start_action = none\n")
	b.WriteString("      }\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	b.WriteString("secrets {\n")
	b.WriteString("  ike-" + name + " {\n")
	b.WriteString("    secret = " + strconv.Quote(psk) + "\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String(), nil
}

func joinShellArgs(args []string) string {
	parts := make([]string, 0, len(args))
	for _, a := range args {
		parts = append(parts, shellQuote(a))
	}
	return strings.Join(parts, " ")
}

// shellQuote makes a single POSIX shell word. pppd's pty option is executed by
// a shell, so every interpolated value is quoted.
func shellQuote(s string) string {
	if s == "" {
		return "''"
	}
	safe := true
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' ||
			strings.ContainsRune("_@%+=:,./-", r)) {
			safe = false
			break
		}
	}
	if safe {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'"
}

func quotePPPOption(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "\"", "\\\"")
	return "\"" + s + "\""
}

// writeGeneratedFiles regenerates all method-specific files and removes stale
// tunneld-generated files. It does not connect anything.
func (l *LinuxOps) writeGeneratedFiles(tunnels []config.Tunnel) error {
	if err := l.ensureLayout(); err != nil {
		return err
	}
	keepSwan := map[string]bool{}
	for _, t := range tunnels {
		if !t.Enabled || t.Method != config.MethodL2TP || !t.UseIPSec {
			continue
		}
		path := swanctlPath(l.cfg.SwanctlDir, t.Name)
		if !l.secrets.Has(t.IPSecSecretRef) {
			_ = os.Remove(path)
			l.log.Warn(t.Name, "IPsec pre-shared key is missing; strongSwan configuration was not generated")
			continue
		}
		content, err := generateSwanctl(l.cfg, l.secrets, t)
		if err != nil {
			return err
		}
		if err := config.WriteFileAtomic(path, []byte(content), 0o600); err != nil {
			return fmt.Errorf("write strongSwan config for %s: %w", t.Name, err)
		}
		keepSwan[t.Name] = true
	}
	// Remove strongSwan files for tunnels that no longer use L2TP/IPsec.
	entries, _ := os.ReadDir(l.cfg.SwanctlDir)
	for _, e := range entries {
		name := e.Name()
		if !strings.HasPrefix(name, "tunneld-") || !strings.HasSuffix(name, ".conf") {
			continue
		}
		base := strings.TrimSuffix(strings.TrimPrefix(name, "tunneld-"), ".conf")
		if !keepSwan[base] {
			_ = os.Remove(filepath.Join(l.cfg.SwanctlDir, name))
		}
	}

	// PPP files are needed for SSTP/PPTP and for L2TP (xl2tpd pppoptfile).
	for _, t := range tunnels {
		if !t.Enabled {
			continue
		}
		path := pppOptionsPath(l.cfg.StateDir, t.Name)
		if !l.secrets.Has(t.PasswordRef) {
			_ = os.Remove(path)
			l.log.Warn(t.Name, "password is missing; PPP options were not generated")
			continue
		}
		content, err := generatePPP(l.cfg, l.secrets, t)
		if err != nil {
			return err
		}
		if err := config.WriteFileAtomic(path, []byte(content), 0o600); err != nil {
			return fmt.Errorf("write PPP options for %s: %w", t.Name, err)
		}
	}
	// Remove stale ppp option files.
	entries, _ = os.ReadDir(filepath.Join(l.cfg.StateDir, "ppp"))
	valid := map[string]bool{}
	for _, t := range tunnels {
		if t.Enabled {
			valid[t.Name] = true
		}
	}
	for _, e := range entries {
		name := strings.TrimSuffix(e.Name(), ".options")
		if !valid[name] {
			_ = os.Remove(filepath.Join(l.cfg.StateDir, "ppp", e.Name()))
		}
	}

	xl := generateXL2TPD(l.cfg, tunnels)
	if err := config.WriteFileAtomic(xl2tpdConfigPath(l.cfg.StateDir), []byte(xl), 0o600); err != nil {
		return fmt.Errorf("write xl2tpd config: %w", err)
	}
	return nil
}

func (l *LinuxOps) ensureLayout() error {
	for _, dir := range []string{
		l.cfg.StateDir,
		filepath.Join(l.cfg.StateDir, "ppp"),
		filepath.Join(l.cfg.StateDir, "ifaces"),
		l.cfg.SwanctlDir,
	} {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return fmt.Errorf("create %s: %w", dir, err)
		}
	}
	return nil
}

// generatedL2TPNames lists enabled L2TP names for config/daemon decisions.
func generatedL2TPNames(tunnels []config.Tunnel) []string {
	var out []string
	for _, t := range tunnels {
		if t.Method == config.MethodL2TP && t.Enabled {
			out = append(out, t.Name)
		}
	}
	sort.Strings(out)
	return out
}
